public class Operations {

    public int Sum(double num1, double num2){
        double result = num1 + num2;
        return (int)result;
    }

    public int Subtract(double num1, double num2){
        double result = num1 - num2;
        return (int)result;
    }

    public int Multiply(double num1, double num2){
        double result = num1 * num2;
        return (int)result;
    }

    public int Divide(double num1, double num2){
        double result = num1 / num2;
        return (int)result;
    }
}
